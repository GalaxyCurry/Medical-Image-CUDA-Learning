// kVp 和 mAs是最关键的两个 —— 一个决定射线 “硬不硬”，一个决定射线 “多不多”

// 只有 kVp 能同时影响射线的「能量（穿透力）」和「强度（光子数量）」，其他任何参数都做不到这一点
// kVp ↑ → 光子能量↑（穿透力更强，能穿透更厚组织），同时光子总数↑ → 整体射线强度↑
// kVp ↓ → 光子能量↓（穿透力变弱），光子数↓ → 射线强度↓

// mAs = mA（管电流）× 曝光时间（s）
// 只决定X 光子的总数量：mAs ↑ → 光子数↑ → 射线强度↑（图像更亮）
// 完全不影响光子能量：无论 mAs 调多高，光子的最大能量始终由 kVp 决定，不会变 “硬”
//////////////////////////////////////////////////////////////////////////////////////////


