// 灰阶与对比度的对应关系： 
// • 高对比度 = 短灰阶（Short Gray-Scale） ：灰阶数量少，明暗对比强烈 
// • 低对比度 = 长灰阶（Long Gray-Scale） ：灰阶数量多，明暗过渡平缓
//////////////////////////////////////////////////////////////////////////////////////////



//////////////////////////////////////////////////////////////////////////////////////////
// 空间分辨率（Spatial Resolution）是衡量放射图像能分辨最小细节的能力
// 通俗来说就是图像够不够「细节丰富、锐利度高、低模糊」
// 它的核心单位是 LP/mm（线对 / 毫米）—— 数值越高，能看清的细微结构就越精细

// 影响因素
// 患者相关因素
//     体型：患者越厚→X 线散射越多→对比度与清晰度下降→空间分辨率降低
//     运动：曝光时任何移动（哪怕呼吸微动）→直接产生运动模糊→分辨率骤降
// 射线束几何因素
//     SID(源像距)：SID 越大→射线越接近平行→几何模糊越小→分辨率越高
//     OID(物像距)：OID 越大→物体离探测器越远→几何模糊越大→分辨率越低
//     FFS(焦点尺寸)：焦点越小→几何模糊越少→分辨率越高（小焦点适合精细部位成像）
//////////////////////////////////////////////////////////////////////////////////////////



//////////////////////////////////////////////////////////////////////////////////////////
//主要曝光参数（Prime Exposure Factors）
//   mAs（管电流 × 时间）：决定光子总数，mAs↑ → 光子数↑ → 暴露量↑
//   kVp（管电压）：决定光子能量，kVp↑ → 穿透力↑ + 光子数↑ → 暴露量↑（+15% kVp ≈ 暴露量翻倍）
//   SID（源像距）：遵循反平方定律，SID↑ → 暴露量↓
//其他影响因素（Influencing Factors）
//   AEC（自动曝光控制）：自动调节曝光量以达到目标剂量
//   Grids（滤线栅）：吸收散射线，需增加曝光量补偿
//   Filtration（滤过）：过滤软射线，减少低能光子，轻微降低暴露量(铜片与铅片)
//   Collimation（准直）：缩小照射野 → 减少散射线 → 降低暴露量
//   Anode Heel Effect（阳极足跟效应）：阳极侧光子少，暴露量更低
//   Patient Factors（患者因素）：体型越厚、密度越高 → 吸收越多 → 暴露量越低
//////////////////////////////////////////////////////////////////////////////////////////
