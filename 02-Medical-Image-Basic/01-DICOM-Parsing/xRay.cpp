//偏差指数（Deviation Index, DI）：评估曝光是否合理
//DI 是衡量实际曝光剂量与目标剂量偏差的指标，正常范围：-2 ~ +2：

//DI 值                   与目标剂量的关系                  图像状态                       处理建议
//3                         ~100% 过高                     饱和伪影                   需降低曝光量重拍
//2                         ~58% 过高                      过曝                       可接受 / 需调整
//1                         ~26% 过高                      轻微过曝                   正常范围
//0                         完全正确                       理想图像                    无需处理
//-1                        ~21% 过低                      轻微欠曝                   正常范围
//-2                        ~37% 过低                      欠曝                       正常范围
//-3                        ~50% 过低                      量子斑点                   需增加曝光量重拍
